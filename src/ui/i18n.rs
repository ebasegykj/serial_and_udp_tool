/// 查文案；缺 key 返回 key 本身（便于发现遗漏）。
pub fn tr(lang: Lang, key: &str) -> &'static str {
    for (k, zh, en) in TABLE {
        if *k == key {
            return match lang {
                Lang::Zh => zh,
                Lang::En => en,
            };
        }
    }
    ""
}
